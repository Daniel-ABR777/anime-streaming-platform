export function searchCatalog(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return catalogAnime;
  return catalogAnime.filter(
    (item) =>
      item.title.toLowerCase().includes(q) ||
      item.genres.some((g) => g.toLowerCase().includes(q)) ||
      item.studio.toLowerCase().includes(q) ||
      item.type.toLowerCase().includes(q),
  );
}

export function countByType(items: CatalogItem[]) {
  return {
    all: items.length,
    tv: items.filter((i) => i.type === "TV Series").length,
    movie: items.filter((i) => i.type === "Movie").length,
    ova: items.filter((i) => i.type === "OVA").length,
    ona: items.filter((i) => i.type === "ONA").length,
    special: items.filter((i) => i.type === "Special").length,
  };
}
